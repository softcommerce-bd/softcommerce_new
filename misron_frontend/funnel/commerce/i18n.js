export function strings(language) {
  return STRINGS[language === "en" ? "en" : "bn"];
}

/** Fills %n / %b / %g placeholders. */
export function fill(text, values) {
  return Object.entries(values).reduce((out, [key, value]) => out.replace(`%${key}`, String(value)), text);
}

/** Why an offer cannot be ordered, in the page's language. */
export function reasonText(t, reason) {
  switch (reason) {
    case "out_of_stock":
      return t.outOfStock;
    case "offer_expired":
      return t.offerEnded;
    case "offer_not_started":
      return t.offerSoon;
    default:
      return t.notOnSale;
  }
}
